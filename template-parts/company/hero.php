<?php
/**
 * Hero of the company pages on a warm tone: copy and actions on one side, the visual on
 * the other (the ingredients in a drop in Nosotros, the word cloud of Peru in Experticia).
 *
 * Arguments:
 * - prefix:    field prefix, frave_about or frave_expertise.
 * - visual:    image or cloud.
 * - secondary: optional [ label, url ] of the second button.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$frave_prefix    = $args['prefix'];
$frave_visual    = $args['visual'] ?? 'image';
$frave_secondary = $args['secondary'] ?? null;
$frave_action    = frave_company_action();
?>
<section class="company-hero company-hero--<?php echo esc_attr( $frave_visual ); ?>" aria-labelledby="company-hero-title">
	<span class="orbit orbit--soft company-hero__orbit" aria-hidden="true"></span>
	<div class="container company-hero__grid">
		<div class="company-hero__copy">
			<p class="eyebrow"><?php echo esc_html( frave_company_text( $frave_prefix . '_hero_eyebrow' ) ); ?></p>
			<h1 class="display company-hero__title" id="company-hero-title"><?php echo frave_emphasis( frave_company_text( $frave_prefix . '_hero_title' ), 'pill' ); // phpcs:ignore WordPress.Security.EscapeOutput -- escaped in the helper. ?></h1>
			<p class="lead company-hero__lead"><?php echo esc_html( frave_company_text( $frave_prefix . '_hero_text' ) ); ?></p>
			<div class="btn-row">
				<?php if ( $frave_action ) : ?>
					<a class="btn btn--primary" href="<?php echo esc_url( $frave_action['url'] ); ?>"<?php echo $frave_action['external'] ? ' target="_blank" rel="noopener"' : ''; ?>>
						<span><?php esc_html_e( 'Solicitar asesoría', 'frave' ); ?></span>
						<?php if ( $frave_action['external'] ) : ?>
							<span class="screen-reader-text"><?php esc_html_e( '(se abre en una nueva pestaña)', 'frave' ); ?></span>
						<?php endif; ?>
						<span class="btn__icon"><?php echo frave_icon( 'arrow-right' ); // phpcs:ignore WordPress.Security.EscapeOutput -- static SVG. ?></span>
					</a>
				<?php endif; ?>
				<?php if ( $frave_secondary ) : ?>
					<?php frave_button( $frave_secondary[0], $frave_secondary[1], 'btn btn--dark', str_starts_with( $frave_secondary[1], '#' ) ? 'chevron-down' : 'arrow-right' ); ?>
				<?php endif; ?>
			</div>
		</div>

		<?php if ( 'cloud' === $frave_visual ) : ?>
			<figure class="word-cloud" data-reveal="fade">
				<?php
				// Generated by bin/nube-peru.py: real text, so it takes the site's font.
				echo file_get_contents( FRAVE_THEME_DIR . '/assets/media/experticia/nube-peru.svg' ); // phpcs:ignore WordPress.Security.EscapeOutput, WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- static theme file.
				?>
				<figcaption class="word-cloud__caption"><?php echo esc_html( frave_company_text( 'frave_expertise_cloud_caption' ) ); ?></figcaption>
				<?php $frave_terms = json_decode( (string) file_get_contents( FRAVE_THEME_DIR . '/assets/media/experticia/nube-peru.json' ), true ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- static theme file. ?>
				<?php if ( is_array( $frave_terms ) ) : ?>
					<ul class="screen-reader-text">
						<?php foreach ( $frave_terms as $frave_term ) : ?>
							<li><?php echo esc_html( $frave_term ); ?></li>
						<?php endforeach; ?>
					</ul>
				<?php endif; ?>
			</figure>
		<?php else : ?>
			<div class="company-hero__media media-frame shape-drop">
				<img src="<?php echo esc_url( frave_asset_url( 'assets/media/empresa/ingredientes.webp' ) ); ?>" width="960" height="960" alt="" fetchpriority="high" decoding="async">
			</div>
		<?php endif; ?>
	</div>
</section>
